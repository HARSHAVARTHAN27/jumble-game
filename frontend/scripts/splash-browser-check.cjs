// Verify the real entry animation with local API fixtures; no live Supabase calls.
const { chromium } = require('playwright')
const { spawn } = require('node:child_process')
const path = require('node:path')
const fs = require('node:fs')
const assert = require('node:assert/strict')
const base = 'http://localhost:5178'
let server, browser
;(async()=>{
  server=spawn(process.execPath,[path.join(__dirname,'../node_modules/vite/bin/vite.js'),'--host','127.0.0.1','--port','5178','--strictPort'],{cwd:path.join(__dirname,'..'),windowsHide:true,stdio:['ignore','pipe','pipe'],env:{...process.env,VITE_DEMO:'false',VITE_SUPABASE_URL:'',VITE_SUPABASE_PUBLISHABLE_KEY:'',VITE_SUPABASE_ANON_KEY:''}})
  await new Promise((resolve,reject)=>{const timeout=setTimeout(()=>reject(new Error('Vite did not start')),20000);server.stdout.on('data',d=>{if(d.toString().includes(':5178/')){clearTimeout(timeout);resolve()}});server.stderr.on('data',d=>process.stderr.write(d));server.on('exit',()=>reject(new Error('Vite exited')))})
  browser=await chromium.launch({headless:true})
  const errors=[]
  const context=await browser.newContext({viewport:{width:1440,height:900}})
  await context.route('**/api/**',route=>route.fulfill({status:404,contentType:'application/json',body:JSON.stringify({success:false,error:{code:'NO_ACTIVE_GAME'}})}))
  await context.addInitScript(()=>{
    window.splashStages=[]
    const observer=new MutationObserver(()=>{
      const scene=document.querySelector('.jumble-splash')?.getAttribute('data-scene')
      if(scene && window.splashStages.at(-1)?.scene!==scene)window.splashStages.push({scene,time:performance.now()})
    })
    observer.observe(document,{attributes:true,attributeFilter:['data-scene'],childList:true,subtree:true})
  })
  const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message))
  fs.mkdirSync(path.join(__dirname,'../test-artifacts'),{recursive:true})
  await page.goto(base,{waitUntil:'domcontentloaded'})
  // Keep the final screenshot opaque; the JS deadline and other animations still run.
  await page.addStyleTag({content:'.jumble-splash { animation-name:none!important; }'})
  await page.locator('.jumble-splash[data-scene="2"]').waitFor()
  assert.equal(await page.locator('.splash-letter').count(),6)
  assert.equal(await page.locator('.splash-underlay').getAttribute('inert'),'')
  await page.screenshot({path:path.join(__dirname,'../test-artifacts/splash-scattered.png')})
  await page.locator('.jumble-splash[data-scene="7"]').waitFor()
  await page.screenshot({path:path.join(__dirname,'../test-artifacts/splash-hero-desktop.png')})
  await page.locator('.jumble-splash').waitFor({state:'detached'})
  const stages=await page.evaluate(()=>window.splashStages)
  assert.deepEqual(stages.map(s=>s.scene),['1','2','3','4','5','6','7'])
  for(const [index,start] of [0,500,1200,2000,2500,3000,3500].entries())assert.ok(Math.abs(stages[index].time-stages[0].time-start)<220,'Scene timing '+(index+1))
  assert.equal(await page.evaluate(()=>sessionStorage.getItem('jumble.splash.seen.v1')),'true')
  await page.locator('.home-headline').waitFor({state:'visible'})
  await page.reload();assert.equal(await page.locator('.jumble-splash').count(),0)
  await page.getByRole('link',{name:'Join Game',exact:true}).click()
  await page.getByLabel('Your name or employee ID').waitFor()
  assert.equal(await page.locator('.jumble-splash').count(),0)
  // Each fresh page load is a fresh entry only after explicitly clearing the per-tab marker.
  // Freeze JS time for layout captures so slow screenshots cannot miss the 500ms final scene.
  await page.clock.install({time:new Date('2026-10-07T12:00:00Z')})
  await page.clock.pauseAt(new Date('2026-10-07T12:00:00Z'))
  for(const [width,height] of [[320,740],[390,844],[844,390]]){
    await page.evaluate(()=>sessionStorage.removeItem('jumble.splash.seen.v1'))
    await page.setViewportSize({width,height})
    await page.goto(base,{waitUntil:'domcontentloaded'})
    await page.addStyleTag({content:'.jumble-splash { animation-name:none!important; }'})
    await page.locator('.jumble-splash[data-scene="1"]').waitFor()
    await page.clock.runFor(3500)
    await page.locator('.jumble-splash[data-scene="7"]').waitFor()
    await page.evaluate(()=>document.getAnimations().forEach(animation=>{
      if(animation.effect?.target?.closest('.jumble-splash'))animation.finish()
    }))
    const bounds=await page.locator('.splash-copy').boundingBox()
    assert.ok(bounds.x>=0 && bounds.x+bounds.width<=width+1 && bounds.y>=0 && bounds.y+bounds.height<height,'Hero fits '+width+'x'+height)
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No horizontal overflow')
    await page.screenshot({path:path.join(__dirname,`../test-artifacts/splash-${width}.png`)})
    await page.clock.runFor(500)
    await page.locator('.jumble-splash').waitFor({state:'detached'})
  }
  await page.clock.resume()
  await page.evaluate(()=>sessionStorage.removeItem('jumble.splash.seen.v1'))
  await page.goto(base+'/play',{waitUntil:'domcontentloaded'})
  const skip=page.getByRole('button',{name:'Skip intro'})
  await skip.focus();await page.keyboard.press('Enter')
  await page.getByLabel('Your name or employee ID').waitFor()
  assert.equal(await page.locator('.jumble-splash').count(),0)
  assert.equal(await page.evaluate(()=>document.activeElement.tagName),'H1')
  await page.evaluate(()=>sessionStorage.removeItem('jumble.splash.seen.v1'))
  await page.goto(base,{waitUntil:'domcontentloaded'})
  await page.getByRole('button',{name:'Skip intro'}).waitFor();await page.keyboard.press('Escape')
  await page.locator('.jumble-splash').waitFor({state:'detached'})
  await page.evaluate(()=>sessionStorage.removeItem('jumble.splash.seen.v1'))
  await page.emulateMedia({reducedMotion:'reduce'});await page.goto(base)
  await page.locator('.home-headline').waitFor({state:'visible'});assert.equal(await page.locator('.jumble-splash').count(),0)
  await page.emulateMedia({reducedMotion:'no-preference'});await page.goto(base+'/control')
  await page.getByRole('heading',{name:'Restricted access'}).waitFor();assert.equal(await page.locator('.jumble-splash').count(),0)
  await page.goto(base+'/game');assert.equal(await page.locator('.jumble-splash').count(),0)
  assert.deepEqual(errors,[])
  console.log('Splash passed: all 7 timed scenes, 4-second handoff, desktop/mobile/landscape, once per tab, direct join, keyboard skip, reduced motion, host/game bypass.')
})().catch(e=>{console.error(e);process.exitCode=1}).finally(async()=>{await browser?.close();server?.kill()})
